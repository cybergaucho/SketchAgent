"""
Simple SketchAgent Playground
Enter a concept/prompt and see the hand-drawn style sketch generated by the LLM.
Supports Anthropic, OpenAI, and free OpenRouter models.
"""

import os
import argparse
from flask import Flask, request, render_template_string, send_from_directory, url_for
from gen_sketch import SketchApp, call_argparse
import traceback

app = Flask(__name__)

# Free vision models on OpenRouter (as of late 2026)
