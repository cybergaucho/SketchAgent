@app.route('/', methods=['GET', 'POST'])
def index():
    concept = request.form.get('concept', 'cat')
    provider = request.form.get('provider', 'openrouter')
    model = request.form.get('model', 'google/gemma-4-31b-it:free')
    seed_mode = request.form.get('seed_mode', 'deterministic')
    error = None
    image_url = None
    svg_url = None
    save_path = None

    if request.method == 'POST':
        try:
            # Build args like the CLI
            parser = argparse.ArgumentParser()
            args = parser.parse_args([])  # empty
            args.concept_to_draw = concept
            args.seed_mode = seed_mode
            args.path2save = "results/playground"
            args.model = model
            args.gen_mode = "generation"
            args.provider = provider
            args.res = 50
            args.cell_size = 12
            args.stroke_width = 7.0
            args.grid_size = (args.res + 1) * args.cell_size
            args.save_name = concept.replace(" ", "_")
            args.path2save = f"{args.path2save}/{args.save_name}"

            os.makedirs(args.path2save, exist_ok=True)

            sketch_app = SketchApp(args)
            sketch_app.generate_sketch()

            # Paths for serving
            png_name = f"{concept.replace(' ', '_')}.png"
            svg_name = f"{concept.replace(' ', '_')}.svg"
            image_url = url_for('serve_result', path=f"{args.save_name}/{png_name}")
            svg_url = url_for('serve_result', path=f"{args.save_name}/{svg_name}")
            save_path = args.path2save

        except Exception as e:
            error = str(e)
            traceback.print_exc()

    return render_template_string(
        HTML,
        concept=concept,
        provider=provider,
        model=model,
        seed_mode=seed_mode,
        free_models=FREE_MODELS,
        error=error,
        image_url=image_url,
        svg_url=svg_url,
        save_path=save_path,
    )

@app.route('/results/<path:path>')
def serve_result(path):
    return send_from_directory('results/playground', path)

if __name__ == '__main__':
    print("Starting SketchAgent Playground at http://127.0.0.1:5000")
    print("Make sure your .env has the right API key (OPENROUTER_API_KEY recommended for free testing).")
    app.run(host='0.0.0.0', port=5000, debug=True)
